const defaultMessages = enMessages

/** Supported full locale tags; used to resolve short codes (e.g. zh -> zh-CN). */
const SUPPORTED_LOCALES = [
    'zh-CN', 'en-US', 'es-ES', 'ar-SA', 'th-TH', 'de-DE', 'ja-JP',
    'pt-BR', 'ru-RU', 'ko-KR', 'id-ID', 'vi-VN', 'fr-FR',
]

/**
 * Resolve language tag to a supported full locale (e.g. 'zh' -> 'zh-CN', 'en' -> 'en-US').
 * @param {string} lang - BCP 47 language tag (e.g. 'zh', 'zh-CN', 'en')
 * @returns {string} resolved full locale or original if no match
 */
export function resolveLocale(lang) {
    const raw = (lang || '').toString().trim()
    if (!raw) return 'en-US'
    const base = raw.split('-')[0].toLowerCase()
    const canonical = SUPPORTED_LOCALES.find(loc => loc.split('-')[0].toLowerCase() === base)
    return canonical || raw
}

/**
 * @param {string} lang - BCP 47 language tag (e.g. 'zh-CN', 'en-US', or short 'zh', 'en')
 * @returns {Record<string, string>} messages for that locale, or default (en)
 */
export function pickMessages(lang) {
    const resolved = resolveLocale(lang)
    if (messages[resolved]) return messages[resolved]
    if (messages[lang]) return messages[lang]
    const base = (lang || '').split('-')[0].toLowerCase()
    const baseKey = Object.keys(messages).find(k => k.split('-')[0].toLowerCase() === base)
    if (baseKey) return messages[baseKey]
    return defaultMessages
}

/**
 * @param {string} locale - resolved locale
 * @returns {(key: string) => string} translation function t(key)
 */
export function createT(locale) {
    const msg = pickMessages(locale)
    return key => msg[key] ?? defaultMessages[key] ?? key
}
